CREATE TABLE produto (
    id_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    categoria VARCHAR(80) NOT NULL,
    preco NUMERIC(10, 2) NOT NULL,
    quantidade_estoque INTEGER NOT NULL,
    estoque_minimo INTEGER NOT NULL,
    CONSTRAINT ck_produto_nome CHECK (length(trim(nome)) > 0),
    CONSTRAINT ck_produto_categoria CHECK (length(trim(categoria)) > 0),
    CONSTRAINT ck_produto_preco CHECK (preco >= 0),
    CONSTRAINT ck_produto_quantidade CHECK (quantidade_estoque >= 0),
    CONSTRAINT ck_produto_minimo CHECK (estoque_minimo >= 0)
);

CREATE TABLE movimentacao (
    id_movimentacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    quantidade INTEGER NOT NULL,
    data_movimentacao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_movimentacao_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto) ON DELETE RESTRICT,
    CONSTRAINT ck_movimentacao_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT ck_movimentacao_quantidade CHECK (quantidade > 0)
);

CREATE INDEX idx_produto_nome ON produto (lower(nome));
CREATE INDEX idx_movimentacao_produto_data
    ON movimentacao (id_produto, data_movimentacao DESC, id_movimentacao DESC);

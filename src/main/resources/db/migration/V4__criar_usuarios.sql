CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(80) NOT NULL UNIQUE,
    senha_hash VARCHAR(60) NOT NULL,
    tentativas INTEGER NOT NULL DEFAULT 0,
    inicio_tentativas TIMESTAMPTZ,
    bloqueado_ate TIMESTAMPTZ,
    CONSTRAINT ck_usuario_login CHECK (login ~ '^[a-z0-9][a-z0-9._-]{2,79}$'),
    CONSTRAINT ck_usuario_tentativas CHECK (tentativas >= 0),
    CONSTRAINT ck_usuario_hash CHECK (senha_hash LIKE '$2a$12$%' OR senha_hash LIKE '$2b$12$%')
);
